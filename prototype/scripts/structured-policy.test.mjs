import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';

const code = ts.transpileModule(readFileSync(new URL('../src/pages/knowledge-config/structuredPolicy.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const policy = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
assert.equal(typeof policy.resolveFieldCapabilities, 'function', '需要统一的平台默认能力解析');
const text = policy.resolveFieldCapabilities('文本');
assert.equal(text.search, true);
assert.equal(text.facet, false);
assert.equal(policy.resolveFieldCapabilities('数值').sort, true);
assert.equal(policy.resolveFieldCapabilities('图片').ai, false);
assert.equal(policy.resolveFieldCapabilities('未知类型').search, false);
assert.equal(policy.resolveFieldCapabilities('文本', { search: false }).search, false);
assert.equal(policy.resolveFieldCapabilities('图片', { search: true }).search, false, '不允许覆盖不支持的能力');
const numberPolicy = policy.mockFieldPoliciesData.find(p => p.type === '数值');
numberPolicy.defaults.facet = true;
assert.equal(policy.resolveFieldCapabilities('数值').facet, true, '新字段读取已保存的平台默认值');
assert.equal(policy.resolveFieldCapabilities('数值', { facet: false }).facet, false, '用户覆盖优先');
console.log('结构化字段默认值、能力限制、用户覆盖：通过');
assert.equal(typeof policy.resolveAggregations, 'function');
assert.deepEqual(policy.resolveAggregations({ type: '数值' }), ['min', 'max']);
assert.deepEqual(policy.resolveAggregations({ type: '文本' }, ['sum', 'distinct']), ['distinct']);
assert.deepEqual(policy.resolveAggregations({ type: '数值', role: 'identifier' }, ['sum', 'avg', 'distinct']), ['distinct']);
assert.deepEqual(policy.resolveAggregations({ type: '图片' }, ['distinct']), []);
assert.deepEqual(policy.resolveAggregations({ type: '未知类型' }, ['sum']), []);
assert.deepEqual(policy.resolveAggregations({ type: '数值' }, []), [], '用户关闭所有统计不应回退默认');
assert.deepEqual(policy.resolveAggregations({ type: '日期' }, ['min', 'avg']), ['min']);
const numeric = policy.mockAggregationPoliciesData.find(p => p.key === 'number');
numeric.defaults = ['min'];
assert.deepEqual(policy.resolveAggregations({ type: '数值' }), ['min']);
assert.deepEqual(policy.resolveAggregations({ type: '数值' }, ['max']), ['max'], '已保存快照不被平台新默认覆盖');
console.log('统计类型限制、标识字段保护、默认继承与覆盖：通过');
const fields = [{ name: 'weight', type: '数值' }];
assert.notEqual(policy.statisticsError(fields, { weight: { operations: ['avg'], note: '' } }, { purpose: '', recordGrain: '一个 SKU' }), '');
assert.notEqual(policy.statisticsError(fields, { weight: { operations: ['sum'], note: '统一 kg' } }, { purpose: '', recordGrain: '' }), '');
assert.equal(policy.statisticsError(fields, { weight: { operations: ['avg'], note: '按 SKU，统一 kg' } }, { purpose: '', recordGrain: '一个 SKU' }), '');
assert.equal(policy.statisticsError(fields, { weight: { operations: ['min'], note: '' } }, { purpose: '', recordGrain: '' }), '');
console.log('求和/平均值口径确认与普通查询无强制填表：通过');
const dataset = { id: 'sample', structuredRecords: [{ weight: 1 }] };
policy.initializeStructuredDefaults(dataset, fields);
assert.equal(dataset.structuredRecordIds[0], 'sample:record:0');
dataset.structuredStatistics.weight.operations = ['max'];
policy.initializeStructuredDefaults(dataset, [...fields, { name: 'name', type: '文本' }]);
assert.deepEqual(dataset.structuredStatistics.weight.operations, ['max']);
assert.equal(dataset.structuredCapabilityDefaults.name.search, true);
const replaced = { id: 'sample', structuredRecords: [{ weight: 2 }] };
policy.initializeStructuredDefaults(replaced, fields);
assert.equal(replaced.structuredRecordIds[0], dataset.structuredRecordIds[0], '替换数据对象后仍有可用记录标识');
